"""Solución - Guiado 1: Operaciones numéricas

Definir a=10, b=3 y mostrar suma, resta, multiplicación y división (2 decimales).
"""

a = 10
b = 3

suma = a + b
resta = a - b
multiplicacion = a * b
division = a / b

print(f"a = {a}, b = {b}")
print(f"Suma: {suma}")
print(f"Resta: {resta}")
print(f"Multiplicación: {multiplicacion}")
print(f"División: {division:.2f}")
